package com.sparktube.app.data

import com.sparktube.app.net.OkHttpDownloader
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import java.net.URLEncoder
import java.util.Locale
import java.util.concurrent.ConcurrentHashMap
import kotlin.math.abs

data class LyricLine(
    val timeMs: Long,
    val text: String
)

data class Lyrics(
    val lines: List<LyricLine>,
    val synced: Boolean
)

object LyricsRepository {

    private val cache = ConcurrentHashMap<String, Lyrics?>()

    suspend fun load(url: String, title: String, artist: String, durationSec: Long): Lyrics? {
        val key = url.ifBlank { "$artist|$title|$durationSec" }
        cache[key]?.let { return it }
        val result = withContext(Dispatchers.IO) {
            fromLrclib(title, artist, durationSec)
        } ?: fromYoutubeCaptions(url)
        if (result != null) cache[key] = result
        return result
    }

    private fun fromLrclib(title: String, artist: String, durationSec: Long): Lyrics? {
        val track = title.substringBefore(" (").substringBefore(" [").substringBefore(" - ").trim()
        val artistName = artist.removeSuffix(" - Topic").removeSuffix("VEVO").trim()
        if (track.isBlank() || artistName.isBlank()) return null
        val qTrack = URLEncoder.encode(track, "UTF-8")
        val qArtist = URLEncoder.encode(artistName, "UTF-8")
        val body = runCatching {
            OkHttpDownloader.getText("https://lrclib.net/api/search?track_name=$qTrack&artist_name=$qArtist")
        }.getOrNull() ?: return null
        val arr = runCatching { JSONArray(body) }.getOrNull() ?: return null
        if (arr.length() == 0) return null
        var bestIdx = 0
        var bestDelta = Long.MAX_VALUE
        for (i in 0 until arr.length()) {
            val obj = arr.optJSONObject(i) ?: continue
            val dur = obj.optDouble("duration", -1.0).toLong()
            val delta = if (durationSec > 0 && dur > 0) abs(dur - durationSec) else i.toLong()
            if (delta < bestDelta) {
                bestDelta = delta
                bestIdx = i
            }
        }
        val hit = arr.optJSONObject(bestIdx) ?: return null
        val synced = hit.optString("syncedLyrics").takeIf { it.isNotBlank() }
        if (synced != null) {
            val lines = parseLrc(synced)
            if (lines.isNotEmpty()) return Lyrics(lines, true)
        }
        val plain = hit.optString("plainLyrics").takeIf { it.isNotBlank() } ?: return null
        val lines = plain.split('\n').map { it.trim() }.filter { it.isNotEmpty() }
            .map { LyricLine(0L, it) }
        return if (lines.isEmpty()) null else Lyrics(lines, false)
    }

    private suspend fun fromYoutubeCaptions(url: String): Lyrics? {
        if (url.isBlank() || url.startsWith("file://")) return null
        val info = runCatching { YtRepository.streamInfo(url) }.getOrNull()
            ?: return null
        val subs = info.subtitles.orEmpty()
        if (subs.isEmpty()) return null
        val pick = subs.firstOrNull { !it.isAutoGenerated && it.extension.equals("vtt", true) }
            ?: subs.firstOrNull { !it.isAutoGenerated }
            ?: subs.firstOrNull { it.extension.equals("vtt", true) }
            ?: subs.firstOrNull()
            ?: return null
        val raw = pick.content?.takeIf { it.isNotBlank() } ?: return null
        val body = if (pick.isUrl) {
            withContext(Dispatchers.IO) {
                runCatching { OkHttpDownloader.getText(raw) }.getOrNull()
            } ?: return null
        } else {
            raw
        }
        val ext = pick.extension.orEmpty().lowercase(Locale.US)
        val lines = when {
            ext.contains("vtt") || body.contains("WEBVTT") -> parseVtt(body)
            ext.contains("srt") -> parseSrt(body)
            else -> parseVtt(body).ifEmpty { parseSrt(body) }
        }
        return if (lines.isEmpty()) null else Lyrics(lines, true)
    }

    private fun parseLrc(raw: String): List<LyricLine> {
        val re = Regex("""\[(\d{1,2}):(\d{2})(?:[.:](\d{1,3}))?]\s*(.*)""")
        return raw.lineSequence().mapNotNull { line ->
            val m = re.find(line.trim()) ?: return@mapNotNull null
            val min = m.groupValues[1].toLong()
            val sec = m.groupValues[2].toLong()
            val frac = m.groupValues[3]
            val ms = when {
                frac.isEmpty() -> 0L
                frac.length == 1 -> frac.toLong() * 100L
                frac.length == 2 -> frac.toLong() * 10L
                else -> frac.take(3).toLong()
            }
            val text = m.groupValues[4].trim()
            if (text.isEmpty()) null else LyricLine(min * 60_000 + sec * 1000 + ms, text)
        }.toList()
    }

    private fun parseVtt(raw: String): List<LyricLine> {
        val cue = Regex("""(\d{1,2}:)?(\d{2}):(\d{2})[.,](\d{3})\s-->\s""")
        val out = mutableListOf<LyricLine>()
        val lines = raw.replace("\r\n", "\n").split('\n')
        var i = 0
        while (i < lines.size) {
            val m = cue.find(lines[i])
            if (m != null) {
                val h = m.groupValues[1].removeSuffix(":").toLongOrNull() ?: 0L
                val min = m.groupValues[2].toLong()
                val sec = m.groupValues[3].toLong()
                val ms = m.groupValues[4].toLong()
                val time = h * 3_600_000 + min * 60_000 + sec * 1000 + ms
                i++
                val text = buildString {
                    while (i < lines.size && lines[i].isNotBlank() && cue.find(lines[i]) == null) {
                        if (isNotEmpty()) append(' ')
                        append(lines[i].replace(Regex("<[^>]+>"), "").trim())
                        i++
                    }
                }.trim()
                if (text.isNotEmpty()) out += LyricLine(time, text)
            } else {
                i++
            }
        }
        return out
    }

    private fun parseSrt(raw: String): List<LyricLine> {
        val cue = Regex("""(\d{2}):(\d{2}):(\d{2})[,.](\d{3})\s-->\s""")
        val out = mutableListOf<LyricLine>()
        val blocks = raw.replace("\r\n", "\n").split(Regex("\n\n+"))
        for (block in blocks) {
            val lines = block.trim().lines()
            val timeLine = lines.firstOrNull { cue.containsMatchIn(it) } ?: continue
            val m = cue.find(timeLine) ?: continue
            val time = m.groupValues[1].toLong() * 3_600_000 +
                m.groupValues[2].toLong() * 60_000 +
                m.groupValues[3].toLong() * 1000 +
                m.groupValues[4].toLong()
            val text = lines.dropWhile { !cue.containsMatchIn(it) }
                .drop(1)
                .joinToString(" ") { it.replace(Regex("<[^>]+>"), "").trim() }
                .trim()
            if (text.isNotEmpty()) out += LyricLine(time, text)
        }
        return out
    }
}
